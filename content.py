# ================= ЛИДЕРБОРД =================
def load_scores(scores_file):
    """Загрузка таблицы рекордов"""
    try:
        with open(scores_file, 'r', encoding='utf-8') as f:
            return json.load(f)
    except Exception:
        return {}


def save_scores(data, scores_file):
    """Сохранение таблицы рекордов"""
    try:
        with open(scores_file, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
    except Exception:
        pass


def get_rank(name, scores):
    """Получить место игрока в рейтинге"""
    board = sorted(scores.items(), key=lambda kv: (-kv[1]['best'], -kv[1]['wins']))
    for i, (n, _) in enumerate(board):
        if n == name:
            return i + 1
    return len(board)